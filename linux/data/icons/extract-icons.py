#!/usr/bin/env python3
# Writes the Linux client's icons as GTK symbolic SVGs, cut from the web
# client's Material Symbols font so every client draws the same artwork.
# Needs fontTools (python3-fonttools); run from the repository root:
#
#    python3 linux/data/icons/extract-icons.py
#
# The output is checked in, so the build does not need fontTools.

import os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.varLib.instancer import instantiateVariableFont

FONT = 'web/material-symbols-rounded.woff2'
OUT  = 'linux/data/icons/scalable/actions'

# GTK icon name (without "gd-" and "-symbolic") -> (glyph, filled)
ICONS = {
	'star':           ('star',          False),
	'star-filled':    ('star',          True),
	'skip-previous':  ('skip_previous', True),
	'skip-next':      ('skip_next',     True),
	'play':           ('play_arrow',    True),
	'pause':          ('pause',         True),
	'add':            ('add',           False),
	'playlist-add':   ('playlist_add',  False),
	'close':          ('close',         False),
	'chevron-left':   ('chevron_left',  False),
	'chevron-right':  ('chevron_right', False),
	'library':        ('library_music', False),
	'playlists':      ('queue_music',   False),
	'recents':        ('history',       False),
	'search':         ('search',        False),
	'settings':       ('settings',      False),
}

def glyphsets():
	sets = {}
	for filled in (False, True):
		f = TTFont(FONT)
		sets[filled] = instantiateVariableFont(f, {'FILL': 1 if filled else 0}).getGlyphSet()
	return sets

def main():
	os.makedirs(OUT, exist_ok=True)
	sets = glyphsets()
	for name, (glyph, filled) in ICONS.items():
		gs = sets[filled]
		if filled and glyph+'.fill' in gs:
			glyph += '.fill'
		pen = SVGPathPen(gs)
		gs[glyph].draw(pen)
		# Font units are y-up on a 960 em; flipping puts the icon in
		# 0..960 of the viewBox.
		svg = ('<?xml version="1.0" encoding="UTF-8"?>\n'
		       '<!-- Material Symbols Rounded "%s" (Apache-2.0), from %s.\n'
		       '     Generated by extract-icons.py; do not hand-edit. -->\n'
		       '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" '
		       'viewBox="0 0 960 960">\n'
		       '  <path transform="matrix(1 0 0 -1 0 960)" d="%s"/>\n'
		       '</svg>\n') % (glyph, FONT, pen.getCommands())
		with open('%s/gd-%s-symbolic.svg' % (OUT, name), 'w') as out:
			out.write(svg)

main()
